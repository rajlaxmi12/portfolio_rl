function renderEditor(domain){
  const data=D[domain];
  document.getElementById('e-fname').textContent=data.fname;
  const body=document.getElementById('e-body');
  body.innerHTML='';
  data.code.forEach((row,i)=>{
    const ln=document.createElement('div');
    ln.className='e-ln';
    ln.style.animationDelay=(i*.08)+'s';
    const num=document.createElement('span');
    num.className='e-num';num.textContent=i+1;
    const code=document.createElement('span');
    code.className='e-code';
    if(Array.isArray(row)){
      let j=0;
      while(j<row.length){
        const cls=row[j];
        if(['ck','cv','cs','cc','ca'].includes(cls)){j++;const sp=document.createElement('span');sp.className=cls;sp.textContent=row[j]||'';code.appendChild(sp);}
        else{code.appendChild(document.createTextNode(cls));}
        j++;
      }
    } else {
      code.textContent=row;
    }
    ln.appendChild(num);ln.appendChild(code);
    body.appendChild(ln);
  });
}
